import React, { useState } from 'react';
import { 
  Sparkles, 
  FileText, 
  Code2, 
  Download, 
  Copy, 
  Check, 
  Save, 
  RefreshCw,
  Sliders,
  AlertCircle
} from 'lucide-react';
import { Button } from '../../components/common/Button';
import { Input, Textarea } from '../../components/common/Input';
import { Card } from '../../components/common/Card';
import { Alert } from '../../components/common/Alert';
import { LoadingSpinner } from '../../components/common/LoadingSpinner';
import { MarkdownRenderer } from '../../components/common/MarkdownRenderer';
import { useToast } from '../../context/ToastContext';
import { api } from '../../services/api';

export const AIToolsTab = ({ project, userRole, onProjectUpdated }) => {
  const { success, error: toastError } = useToast();

  const [activeTool, setActiveTool] = useState('readme'); // 'readme' | 'docs'

  // README Generator Form State
  const [readmeName, setReadmeName] = useState(project.name || '');
  const [readmeDesc, setReadmeDesc] = useState(project.description || '');
  const [features, setFeatures] = useState('Lightweight project workspaces, Markdown notes with AI assist, file uploads with code syntax preview, team collaboration');
  const [techStack, setTechStack] = useState('Node.js, Express, React, Vite, Tailwind CSS, MongoDB, Google Gemini AI');
  const [installSteps, setInstallSteps] = useState('npm install in client and server, configure .env, run npm run dev');
  const [codeContext, setCodeContext] = useState('');

  // Results
  const [generatedReadme, setGeneratedReadme] = useState(project.readme || '');
  const [isReadmeEditing, setIsReadmeEditing] = useState(false);
  const [readmeLoading, setReadmeLoading] = useState(false);
  const [readmeSaving, setReadmeSaving] = useState(false);
  const [copied, setCopied] = useState(false);
  const [apiError, setApiError] = useState('');

  // Code Docs Generator State
  const [docCodeInput, setDocCodeInput] = useState('');
  const [docLanguage, setDocLanguage] = useState('javascript');
  const [generatedDocs, setGeneratedDocs] = useState('');
  const [docLoading, setDocLoading] = useState(false);
  const [docCopied, setDocCopied] = useState(false);

  const canSave = userRole === 'owner' || userRole === 'admin';

  // Generate README handler
  const handleGenerateReadme = async (e) => {
    e.preventDefault();
    setApiError('');
    setReadmeLoading(true);

    try {
      const res = await api.post('/gemini/readme', {
        projectName: readmeName.trim(),
        description: readmeDesc.trim(),
        features: features.trim(),
        techStack: techStack.trim(),
        installSteps: installSteps.trim(),
        codeContext: codeContext.trim(),
      });

      setGeneratedReadme(res.readme || res.result || '');
      setIsReadmeEditing(false);
      success('README.md generated by Gemini!');
    } catch (err) {
      setApiError(err.message || 'Failed to generate README. Check your Gemini API configuration.');
    } finally {
      setReadmeLoading(false);
    }
  };

  // Save README to Project
  const handleSaveReadmeToProject = async () => {
    if (!generatedReadme) return;
    try {
      setReadmeSaving(true);
      await api.patch(`/projects/${project._id}`, {
        readme: generatedReadme,
      });
      success('README saved to project documentation!');
      if (onProjectUpdated) onProjectUpdated();
    } catch (err) {
      toastError(err.message || 'Failed to save README to project');
    } finally {
      setReadmeSaving(false);
    }
  };

  // Download README.md
  const handleDownloadReadme = () => {
    if (!generatedReadme) return;
    const blob = new Blob([generatedReadme], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'README.md';
    a.click();
    URL.revokeObjectURL(url);
    success('Downloaded README.md');
  };

  const handleCopyReadme = () => {
    if (!generatedReadme) return;
    navigator.clipboard.writeText(generatedReadme);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  // Generate Code Documentation
  const handleGenerateDocs = async (e) => {
    e.preventDefault();
    if (!docCodeInput.trim()) return;

    setDocLoading(true);
    setApiError('');

    try {
      const res = await api.post('/gemini/docs', {
        code: docCodeInput.trim(),
        language: docLanguage,
      });

      setGeneratedDocs(res.documentation || res.result || '');
      success('Documentation generated!');
    } catch (err) {
      setApiError(err.message || 'Failed to generate documentation.');
    } finally {
      setDocLoading(false);
    }
  };

  return (
    <div className="space-y-6 max-w-5xl animate-fade-in">
      {/* Tool Selector Header */}
      <div className="bg-[#12161f] border border-[#232936] rounded-xl p-4 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2.5">
          <div className="w-8 h-8 rounded-lg bg-indigo-600/10 border border-indigo-500/30 flex items-center justify-center text-indigo-400">
            <Sparkles className="w-4 h-4" />
          </div>
          <div>
            <h2 className="text-sm font-semibold text-slate-100">Gemini Developer AI Toolkit</h2>
            <p className="text-xs text-slate-400">Generate structured READMEs, technical documentation, and code explanations.</p>
          </div>
        </div>

        <div className="flex items-center bg-[#181d28] border border-[#273042] rounded-lg p-0.5 text-xs">
          <button
            onClick={() => setActiveTool('readme')}
            className={`px-3 py-1.5 rounded-md font-medium transition-colors ${
              activeTool === 'readme' ? 'bg-indigo-600 text-white' : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            README Generator
          </button>
          <button
            onClick={() => setActiveTool('docs')}
            className={`px-3 py-1.5 rounded-md font-medium transition-colors ${
              activeTool === 'docs' ? 'bg-indigo-600 text-white' : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            Code Documenter
          </button>
        </div>
      </div>

      {apiError && (
        <Alert variant="danger">
          <p className="font-semibold mb-0.5">AI Service Error</p>
          <p>{apiError}</p>
          <p className="mt-1 text-slate-400 text-[11px]">
            Please check that GEMINI_API_KEY is configured in your server .env file.
          </p>
        </Alert>
      )}

      {/* Tool 1: README Generator */}
      {activeTool === 'readme' && (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          {/* Inputs Column */}
          <div className="lg:col-span-5 bg-[#12161f] border border-[#232936] rounded-xl p-5 space-y-4">
            <div className="flex items-center gap-2 pb-3 border-b border-[#1f2532] text-slate-200 text-xs font-semibold">
              <Sliders className="w-3.5 h-3.5 text-indigo-400" />
              <span>Project Specifications</span>
            </div>

            <form onSubmit={handleGenerateReadme} className="space-y-3.5">
              <Input
                label="Project Name"
                value={readmeName}
                onChange={(e) => setReadmeName(e.target.value)}
                required
                className="text-xs"
              />

              <Textarea
                label="Project Overview & Purpose"
                rows={2}
                value={readmeDesc}
                onChange={(e) => setReadmeDesc(e.target.value)}
                placeholder="Core objective of the application..."
                className="text-xs"
              />

              <Textarea
                label="Key Features (comma or line separated)"
                rows={3}
                value={features}
                onChange={(e) => setFeatures(e.target.value)}
                placeholder="User auth, Markdown notes, File previews..."
                className="text-xs"
              />

              <Input
                label="Technology Stack"
                value={techStack}
                onChange={(e) => setTechStack(e.target.value)}
                placeholder="React, Vite, Express, MongoDB..."
                className="text-xs"
              />

              <Input
                label="Setup & Run Commands"
                value={installSteps}
                onChange={(e) => setInstallSteps(e.target.value)}
                placeholder="npm install, npm run dev..."
                className="text-xs"
              />

              <Textarea
                label="Optional Code or Architectural Snippets"
                rows={2}
                value={codeContext}
                onChange={(e) => setCodeContext(e.target.value)}
                placeholder="Paste route summaries or config structure..."
                className="text-xs"
              />

              <Button
                type="submit"
                variant="primary"
                size="sm"
                className="w-full text-xs"
                isLoading={readmeLoading}
                icon={Sparkles}
              >
                Generate README.md
              </Button>
            </form>
          </div>

          {/* Results Column */}
          <div className="lg:col-span-7 bg-[#12161f] border border-[#232936] rounded-xl overflow-hidden flex flex-col">
            <div className="p-3.5 border-b border-[#1f2532] bg-[#141822] flex items-center justify-between gap-2 flex-wrap">
              <div className="flex items-center gap-2">
                <FileText className="w-4 h-4 text-indigo-400" />
                <span className="text-xs font-semibold text-slate-200">README.md Draft</span>
              </div>

              {generatedReadme && (
                <div className="flex items-center gap-1.5 flex-wrap">
                  <button
                    onClick={() => setIsReadmeEditing(!isReadmeEditing)}
                    className="px-2.5 py-1 text-xs rounded border border-[#273042] bg-[#181d28] hover:bg-[#202736] text-slate-300 transition-colors"
                  >
                    {isReadmeEditing ? 'Preview' : 'Edit Markdown'}
                  </button>

                  <Button size="sm" variant="outline" onClick={handleCopyReadme}>
                    {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copied ? 'Copied' : 'Copy'}</span>
                  </Button>

                  <Button size="sm" variant="outline" icon={Download} onClick={handleDownloadReadme}>
                    Download
                  </Button>

                  {canSave && (
                    <Button
                      size="sm"
                      variant="primary"
                      icon={Save}
                      isLoading={readmeSaving}
                      onClick={handleSaveReadmeToProject}
                    >
                      Save to Project
                    </Button>
                  )}
                </div>
              )}
            </div>

            <div className="p-5 flex-1 overflow-y-auto min-h-[450px]">
              {readmeLoading ? (
                <LoadingSpinner text="Generating comprehensive README with Gemini..." />
              ) : generatedReadme ? (
                isReadmeEditing ? (
                  <textarea
                    value={generatedReadme}
                    onChange={(e) => setGeneratedReadme(e.target.value)}
                    className="w-full h-full min-h-[400px] bg-[#0c0e13] border border-[#232936] rounded-lg p-3.5 font-mono text-xs text-slate-200 focus:outline-none focus:ring-1 focus:ring-indigo-500 resize-none leading-relaxed"
                  />
                ) : (
                  <MarkdownRenderer content={generatedReadme} />
                )
              ) : (
                <div className="text-center py-16 text-xs text-slate-400">
                  <p className="mb-1 font-semibold text-slate-300">No README draft generated yet</p>
                  <p>Fill out the specifications on the left and click "Generate README.md".</p>
                </div>
              )}
            </div>
          </div>
        </div>
      )}

      {/* Tool 2: Code Documenter */}
      {activeTool === 'docs' && (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          <div className="lg:col-span-6 bg-[#12161f] border border-[#232936] rounded-xl p-5 space-y-4">
            <div className="flex items-center justify-between pb-3 border-b border-[#1f2532]">
              <span className="text-xs font-semibold text-slate-200">Input Code Snippet</span>
              <select
                value={docLanguage}
                onChange={(e) => setDocLanguage(e.target.value)}
                className="bg-[#0e1117] border border-[#232936] text-xs text-slate-300 rounded px-2 py-1"
              >
                <option value="javascript">JavaScript</option>
                <option value="typescript">TypeScript</option>
                <option value="python">Python</option>
                <option value="html">HTML</option>
                <option value="css">CSS</option>
                <option value="json">JSON</option>
              </select>
            </div>

            <form onSubmit={handleGenerateDocs} className="space-y-4">
              <textarea
                value={docCodeInput}
                onChange={(e) => setDocCodeInput(e.target.value)}
                placeholder="Paste function, module, API route, or component code here..."
                rows={14}
                className="w-full bg-[#0c0e13] border border-[#232936] rounded-lg p-3.5 font-mono text-xs text-slate-200 focus:outline-none focus:ring-1 focus:ring-indigo-500 leading-relaxed"
                required
              />

              <Button
                type="submit"
                variant="primary"
                size="sm"
                className="w-full text-xs"
                isLoading={docLoading}
                icon={Sparkles}
              >
                Generate Technical Documentation
              </Button>
            </form>
          </div>

          <div className="lg:col-span-6 bg-[#12161f] border border-[#232936] rounded-xl overflow-hidden flex flex-col">
            <div className="p-3.5 border-b border-[#1f2532] bg-[#141822] flex items-center justify-between">
              <span className="text-xs font-semibold text-slate-200">Generated Documentation</span>
              {generatedDocs && (
                <Button
                  size="sm"
                  variant="outline"
                  onClick={() => {
                    navigator.clipboard.writeText(generatedDocs);
                    setDocCopied(true);
                    setTimeout(() => setDocCopied(false), 2000);
                  }}
                >
                  {docCopied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                  <span>{docCopied ? 'Copied' : 'Copy'}</span>
                </Button>
              )}
            </div>

            <div className="p-5 flex-1 overflow-y-auto min-h-[400px]">
              {docLoading ? (
                <LoadingSpinner text="Generating documentation with Gemini..." />
              ) : generatedDocs ? (
                <MarkdownRenderer content={generatedDocs} />
              ) : (
                <div className="text-center py-16 text-xs text-slate-400">
                  <p className="mb-1 font-semibold text-slate-300">No documentation generated yet</p>
                  <p>Paste your code on the left and submit.</p>
                </div>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
